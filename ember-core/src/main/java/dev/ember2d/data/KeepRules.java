package dev.ember2d.data;

import com.badlogic.gdx.utils.reflect.ClassReflection;
import com.badlogic.gdx.utils.reflect.ReflectionException;
import dev.ember2d.core.PublicApi;
import java.io.File;
import java.io.FileOutputStream;
import java.io.IOException;
import java.io.OutputStreamWriter;
import java.io.Writer;
import java.nio.charset.StandardCharsets;
import java.util.LinkedHashSet;
import java.util.Set;

/**
 * Generates R8 keep rules for every registered component (F-010, S-04), so data can still find their fields by name in
 * a minified Android build. Run at build time with a game's {@link ComponentSetup} class and an output file:
 * {@code java dev.ember2d.data.KeepRules com.example.MyComponents build/generated/ember-keep-rules.pro}.
 *
 * <p>Per component: {@code -keep class X { <init>(); <fields>; }}; per enum used in a component field:
 * {@code -keep enum E { *; }}.
 */
@PublicApi
public final class KeepRules {

    private KeepRules() {
    }

    public static void main(String[] args) throws IOException {
        if (args.length != 2) {
            throw new IllegalArgumentException("Usage: KeepRules <ComponentSetup class> <output file>");
        }
        ComponentRegistry registry = new ComponentRegistry();
        setup(args[0]).register(registry);
        File out = new File(args[1]);
        File dir = out.getAbsoluteFile().getParentFile();
        if (dir != null && !dir.isDirectory() && !dir.mkdirs()) {
            throw new IOException("Cannot create " + dir);
        }
        try (Writer w = new OutputStreamWriter(new FileOutputStream(out), StandardCharsets.UTF_8)) {
            w.write(rules(registry, args[0]));
        }
    }

    /** The rules for a registry; {@code source} names the setup in the header comment. */
    public static String rules(ComponentRegistry registry, String source) {
        StringBuilder b = new StringBuilder();
        b.append("# Generated by dev.ember2d.data.KeepRules from ").append(source).append(" - do not edit.\n");
        b.append("# Registered components keep their constructor and field names (F-010, S-04).\n");
        Set<Class<?>> enums = new LinkedHashSet<>();
        for (String name : registry.names()) {
            ComponentRegistry.Type type = registry.type(name);
            b.append("-keep class ").append(type.type.getName()).append(" {\n    <init>();\n    <fields>;\n}\n");
            for (FieldSetter field : type.fields.values()) {
                if (field.kind == FieldSetter.Kind.ENUM) {
                    enums.add(field.type);
                }
            }
        }
        for (Class<?> e : enums) {
            b.append("-keep enum ").append(e.getName()).append(" { *; }\n");
        }
        return b.toString();
    }

    private static ComponentSetup setup(String className) {
        try {
            Class<?> type = ClassReflection.forName(className);
            Object setup = ClassReflection.newInstance(type);
            if (!(setup instanceof ComponentSetup s)) {
                throw new IllegalArgumentException(className + " does not implement " + ComponentSetup.class.getName());
            }
            return s;
        } catch (ReflectionException e) {
            throw new IllegalArgumentException("Cannot create " + className + " (needs a public no-argument "
                    + "constructor)", e);
        }
    }
}
