/**
 * A level of the platformer demo (F-015, I-170, I-250), edited in Tiled ({@code maps/level<N>.tmx}).
 * <ul>
 *   <li>Movement comes from {@code kit-platformer} (I-200). Level 1 uses none of its optional mechanics; level 2
 *       switches on wall slide and wall jump, level 3 an air jump and dash (X or Left Shift). Each map switches them on
 *       with a class-typed {@code PlatformerBody} property on its player object (I-245); the dev tools inspector can
 *       switch them live.</li>
 *   <li>The player (Ninja Frog) runs with acceleration, jumps with variable height, coyote time and jump buffering, and
 *       drops through one-way planks with down + jump.</li>
 *   <li>Pigs patrol; landing on one defeats it, touching it otherwise hurts. Spikes hurt. A hurt player respawns at the
 *       last checkpoint flag. The trophy ends the level with the time and deaths, saves the progress (save slot 0)
 *       and unlocks the next level.</li>
 *   <li>Everything is placed in Tiled as prefab objects (F-009, F-010); saving the map in a dev run restarts the scene
 *       with the changes (hot reload, I-150). F1 opens the dev tools (I-160), F3 the collider view.</li>
 *   <li>Audio (I-210): level music, and sounds for jumps, stomps, hurt, checkpoints and the goal; pause pauses the
 *       music. The sounds are generated by {@code assets-src/demo-platformer/sound/make_sounds.py}.</li>
 *   <li>UI (I-220): a HUD with the time and deaths; {@code pause} (P, double tap, touch II) or {@code menu} (Escape,
 *       Android back, long press) pauses the game and opens the pause menu (resume, restart, settings, main menu);
 *       the goal shows a results panel (next level, play again, main menu).</li>
 *   <li>On-screen controls (I-122, touch screens or desktop {@code --touch-controls}): a floating joystick on the
 *       left half runs, button A jumps, button II pauses.</li>
 * </ul>
 */
final class DemoScene extends Scene {

    private static final Log LOG = Log.get("demo");

    private Input input;
    private int player;
    private LevelSystem level;
    private HudCounter time;
    private HudCounter deaths;
    private Table pausePanel;
    private final Levels.Level info;

    private boolean paused;
    private boolean dashShown = true;

    /** Level {@code number}, 1 to {@link Levels#count()}. */
    DemoScene(int number) {
        this.info = Levels.get(number);
    }

    /** The level's asset group (its map), preloaded by the main menu (I-240). */
    @Override
    protected String assetGroup() {
        return info.group();
    }

    @Override
    protected void enter(EngineContext context) {
        World world = world();
        input = context.input();
        context.renderer().setLayers(new RenderLayer("background", SortMode.NONE), new RenderLayer("world", SortMode.Z),
                new RenderLayer("foreground", SortMode.NONE));
        TileMap map = TileMap.load(context.assets(), info.mapId(), context.renderer().pixelsPerUnit());
        Collision collision = new Collision(world, context.events());
        collision.addTileGrid(map.collision(), 0);
        LOG.info("Map " + map.source() + ": " + map.width() + "x" + map.height() + " tiles, "
                + map.collision().solidCount() + " solid, " + map.collision().oneWayCount() + " one-way");

        IntArray placed = new MapSpawner(context.prefabs()).spawn(world, map);
        LOG.info("Spawned " + placed.size + " entities from the map");
        player = world.findByName("player");
        PlatformerBody body = world.get(player, PlatformerBody.class);
        LOG.info("Player mechanics (from the map): air jumps " + body.airJumps + ", dash " + body.dash
                + ", wall jump " + (body.wallSlide && body.wallJump));

        world.get(world.findByName("camera"), CameraFollow.class).bounds = map.bounds(new Rectangle());

        world.addSystem(new MovingPlatformSystem(world, collision));   // solids first: riders see where they are
        world.addSystem(new PatrollerSystem(world, collision));
        world.addSystem(new PlatformerSystem(world, collision, input, context.events()));
        world.addSystem(new CollisionSystem(world, collision));        // after all movement: hash and triggers
        level = new LevelSystem(world, collision, context.events());
        world.addSystem(level);
        world.addSystem(new CameraFollowSystem(world, context.renderer().camera(), context.time()));
        AnimationLibrary clips = new AnimationLibrary(context.assets());
        world.addSystem(new AsmSystem(world, new AsmLibrary(context.assets(), clips), context.events()));
        world.addSystem(new AnimationSystem(world, clips, context.events()));   // after the state machine
        SpriteRenderSystem sprites = new SpriteRenderSystem(world, context.renderer(), context.assets(), context.time());
        world.addSystem(sprites);
        new TileMapRenderer(map, context.renderer(), context.time()).attachTo(sprites);
        new TextRenderer(world, context.renderer(), context.assets(), context.time()).attachTo(sprites);
        world.addSystem(new CollisionDebugSystem(world, collision, context.debug(), context.renderer()));

        context.events().on(InputContextChanged.class, e -> LOG.info("Input context: " + e.top()));
        Audio audio = context.audio();
        audio.playMusic("music.level", 0.5f);
        context.events().on(Jumped.class, e -> audio.playVaried("sfx.jump", 0.06f));
        context.events().on(EnemyStomped.class, e -> audio.play("sfx.stomp"));
        context.events().on(PlayerHurt.class, e -> {
            audio.play("sfx.hurt");
            input.vibrate(40);   // a short buzz on phones (I-225)
        });
        context.events().on(CheckpointReached.class, e -> audio.play("sfx.checkpoint"));
        context.events().on(LevelCompleted.class, e -> {
            LOG.info("Level complete in " + LevelSystem.clock(e.seconds()) + " with " + e.deaths() + " death(s)");
            audio.stopMusic(1f);
            audio.play("sfx.goal");
            showResults(e);
        });
        context.events().on(AnimationEvent.class, e -> {
            if (e.entity() == player && e.name().equals("step")) {
                LOG.debug("Footstep");   // a frame event from the run clip (dev builds log DEBUG)
            }
        });
        context.events().on(ActorSquished.class, e -> {
            if (e.actor() == player) {
                LOG.info("Squished by " + world.name(e.solid()));
            }
        });

        Ui ui = ui();
        DemoUi.useSkin(ui, context.assets());
        Table hud = new Table(ui.skin());
        time = new HudCounter(ui.skin(), "Time", null);
        deaths = new HudCounter(ui.skin(), "Deaths", null);
        hud.add(time).left().row();
        hud.add(deaths).left().padTop(2f);
        ui.root().add(hud).expand().top().left().pad(4f);
    }

    // ---- pause menu ----

    private void openPause() {
        if (paused || level.complete()) {
            return;
        }
        paused = true;
        context().time().setPaused(true);
        context().audio().pauseMusic();
        input.pushContext("ui");
        pausePanel = DemoUi.overlay(ui());
        showPauseMenu();
        LOG.info("Paused");
    }

    private void showPauseMenu() {
        Ui ui = ui();
        MenuList menu = new MenuList(ui);
        menu.add("Resume", this::closePause);
        menu.add("Restart level", () -> context().scenes().restart());
        menu.add("Settings", this::showPauseSettings);
        menu.add("Main menu", () -> ConfirmDialog.show(ui, "Quit to the main menu?", "Yes", "No",
                () -> context().scenes().replace(new MenuScene(), Transition.fade(0.5f))));
        menu.onBack(this::closePause);
        DemoUi.show(pausePanel, "Paused", menu);
    }

    private void showPauseSettings() {
        DemoUi.show(pausePanel, "Settings", DemoUi.settings(ui(), context(), this::showPauseMenu,
                this::showPauseSettings));
    }

    private void closePause() {
        if (!paused) {
            return;
        }
        paused = false;
        pausePanel.getParent().remove();
        input.popContext();
        context().time().setPaused(false);
        context().audio().resumeMusic();
        LOG.info("Running");
    }

    // ---- results ----

    private void showResults(LevelCompleted e) {
        Ui ui = ui();
        input.pushContext("ui");
        Table panel = DemoUi.overlay(ui);
        Progress.load(context().saves()).completed(info.number(), e.seconds());   // unlocks the next level (I-250)
        MenuList menu = new MenuList(ui);
        boolean last = info.number() == Levels.count();
        if (!last) {
            menu.add("Next level", () -> context().scenes().replace(new DemoScene(info.number() + 1),
                    Transition.fade(0.5f)));
        }
        menu.add("Play again", () -> context().scenes().replace(new DemoScene(info.number()), Transition.fade(0.5f)));
        menu.add("Main menu", () -> context().scenes().replace(new MenuScene(), Transition.fade(0.5f)));
        DemoUi.show(panel, last ? "You finished the demo!" : "Level " + info.number() + " complete!", menu);
        Table stats = new Table(ui.skin());
        stats.add(new Label("Time   " + LevelSystem.clock(e.seconds()), ui.skin())).left().row();
        stats.add(new Label("Deaths " + e.deaths(), ui.skin())).left().row();
        // The best time is global data: kept across runs, not tied to a save slot (I-230).
        SaveData global = context().saves().global();
        float best = global.getFloat(info.bestTimeKey(), Float.MAX_VALUE);
        if (e.seconds() < best) {
            global.set(info.bestTimeKey(), e.seconds());
            context().saves().flush();
            stats.add(new Label(best == Float.MAX_VALUE ? "First clear!" : "New best!", ui.skin(), "title"))
                    .left().padTop(2f);
        } else {
            stats.add(new Label("Best   " + LevelSystem.clock(best), ui.skin())).left();
        }
        panel.getCells().get(0).padBottom(4f);
        panel.row();
        panel.add(stats).padTop(6f);
    }

    @Override
    protected void exit() {
        while (!"gameplay".equals(input.topContext())) {
            input.popContext();
        }
        if (context().time().paused()) {
            context().time().setPaused(false);
            context().audio().resumeMusic();
        }
    }

    @Override
    protected void update(float delta) {
        if ("gameplay".equals(input.topContext()) && (input.justPressed("pause") || input.justPressed("menu"))) {
            openPause();
        }
        time.setSeconds(level.levelTime());
        deaths.setValue(level.deaths());
        boolean dash = world().get(player, PlatformerBody.class).dash;
        if (dash != dashShown) {
            dashShown = dash;
            input.setTouchButtonVisible("dash", dash);   // the B button appears once dash is switched on (I-225)
        }
    }
}
